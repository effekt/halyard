#!/usr/bin/env node

// Keeps `NUBBIN_VERSION` equal to the version in `packages/core/package.json`.
//
// `compile` stamps it into every artifact as `compiledWith`, so an artifact records what
// produced it. The constant was hand-written and never moved: `0.1.0-rc.0` shipped stamping
// `0.0.0`, which makes the field worse than absent — it looks like an answer.
//
// Generated rather than asserted, because changesets bumps the manifest and nothing else. A
// check that only complained would fail every release and be fixed by hand each time.
//
// Usage: node scripts/sync-core-version.mjs [--check]

import { readFile, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const MANIFEST = join(ROOT, "packages/core/package.json");
const CONSTANT = join(ROOT, "packages/core/src/version.constants.ts");

const { version } = JSON.parse(await readFile(MANIFEST, "utf8"));
const expected = `/** Stamped into every artifact as \`compiledWith\`, so an artifact records what produced it. */
// Generated by scripts/sync-core-version.mjs from packages/core/package.json. Do not edit.
export const NUBBIN_VERSION = ${JSON.stringify(version)};
`;

const actual = await readFile(CONSTANT, "utf8");
if (actual === expected) {
  console.log(`✅ NUBBIN_VERSION is ${version}, matching the manifest.`);
  process.exit(0);
}

if (!process.argv.includes("--check")) {
  await writeFile(CONSTANT, expected);
  console.log(`✅ NUBBIN_VERSION set to ${version}.`);
  process.exit(0);
}

console.log(
  `❌ NUBBIN_VERSION does not match packages/core/package.json (${version}).\n\n` +
    "   Every artifact records this as compiledWith, so a stale value misreports what\n" +
    "   produced it. Run `pnpm sync-version` to regenerate.\n",
);
process.exit(1);
